def find(code: str):
    """Kod bo'yicha stansiya. Topilmasa None."""
    return STATIONS.get((code or "").strip())


def search(query: str, limit: int = 20) -> list[dict]:
    """Kod yoki nom bo'yicha qidirish -- formadagi tanlash ro'yxati uchun."""
    text = (query or "").strip().lower()
    found = []
    for code, (cyr, latin, lat, lon, near) in STATIONS.items():
        if text and text not in code and text not in cyr.lower() and text not in latin.lower():
            continue
        found.append({
            "code": code,
            "name": cyr,
            "name_latin": latin,
            "latitude": lat,
            "longitude": lon,
            "nearby": near,
        })
        if len(found) >= limit:
            break
    return found
