def main() -> int:
    db = SessionLocal()
    regions = {region.name: region for region in db.query(Region).all()}

    missing = sorted(set(DISTRICTS) - set(regions))
    if missing:
        print("Bu viloyatlar ma'lumotnomada yo'q, o'tkazib yuborildi:")
        for name in missing:
            print(f"  - {name}")

    added = 0
    for region_name, names in DISTRICTS.items():
        region = regions.get(region_name)
        if not region:
            continue
        have = {district.name for district in region.districts}
        for name in names:
            if name in have:
                continue
            db.add(District(region_id=region.id, name=name))
            have.add(name)
            added += 1
    db.commit()

    print(f"\nQo'shildi: {added} ta")
    print("Viloyatlar bo'yicha:")
    for region in db.query(Region).order_by(Region.name).all():
        print(f"  {region.name:<32} {len(region.districts):>3}")
    print(f"  {'JAMI':<32} {db.query(District).count():>3}")
    db.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
